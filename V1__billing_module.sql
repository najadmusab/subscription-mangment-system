CREATE TABLE IF NOT EXISTS tax_rates (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL,
 rate_percent DECIMAL(7,3) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS discounts (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL, type VARCHAR(20) NOT NULL,
 value DECIMAL(14,2) NOT NULL, minimum_purchase DECIMAL(14,2) NOT NULL DEFAULT 0,
 minimum_quantity INT NOT NULL DEFAULT 1, starts_at DATETIME NULL, ends_at DATETIME NULL,
 usage_limit INT NULL, used_count INT NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
